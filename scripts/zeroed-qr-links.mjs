#!/usr/bin/env node
// Zeroed YouTube end-card QR links (founder, 12 Nov 2026).
//
// Every Zeroed long video ends on a QR code that takes the viewer to https://www.stillwareltd.com/zeroed/.
// The code itself encodes a short link per series, https://www.stillwareltd.com/z/<series-slug>. That
// keeps the QR small enough to scan off a TV across a room, and it tells us which series the scan came from.
// Each short link is a 302 to /zeroed/?utm_source=youtube&utm_medium=qr&utm_campaign=yt-z-<series-slug>.
// The canonical on /zeroed/ stays https://www.stillwareltd.com/zeroed/, so the tagged URL is never indexed
// on its own. On arrival, Layout.astro's campaign script tags the App Store link (ct=yt-z-qr-<slug>) and
// the Google Play link (referrer=utm_*), so a download from a scan is counted per series in
// App Store Connect and Play Console.
//
//   node scripts/zeroed-qr-links.mjs           rewrite the generated block in public/_redirects from src/data/zeroed-qr.json
//   node scripts/zeroed-qr-links.mjs --check   exit 1 if the block is missing or out of date (runs in `npm run build`)
//   node scripts/zeroed-qr-links.mjs --list    print each series' QR URL (what the video's code must encode)
//
// The block sits between the BEGIN and END marker lines below. Edit src/data/zeroed-qr.json, never the block.
// Policy: the /z/ paths are new (none is in seo/protected-urls.txt); log changes in seo/CHANGES.md.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(ROOT, 'src/data/zeroed-qr.json');
const REDIRECTS = join(ROOT, 'public/_redirects');
const SITE = 'https://www.stillwareltd.com';
const BEGIN = '# BEGIN zeroed-qr (generated by scripts/zeroed-qr-links.mjs from src/data/zeroed-qr.json; do not edit by hand)';
const END = '# END zeroed-qr';
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const APPLE_CT_MAX = 40; // App Store Connect campaign tokens are limited to 40 characters.

function load() {
  const data = JSON.parse(readFileSync(DATA, 'utf8'));
  const dest = data.destination || '/zeroed/';
  const seen = new Set();
  for (const s of data.series) {
    if (!SLUG.test(s.slug)) throw new Error(`zeroed-qr: bad slug "${s.slug}" (lowercase letters, digits and single hyphens)`);
    if (seen.has(s.slug)) throw new Error(`zeroed-qr: duplicate slug "${s.slug}"`);
    seen.add(s.slug);
    const ct = `yt-z-qr-${s.slug}`;
    if (ct.length > APPLE_CT_MAX) throw new Error(`zeroed-qr: App Store token "${ct}" is longer than ${APPLE_CT_MAX} characters`);
  }
  return { dest, series: data.series };
}

export function block({ dest, series }) {
  const to = (campaign) => `${dest}?utm_source=youtube&utm_medium=qr&utm_campaign=${campaign}`;
  const lines = [BEGIN, `# Zeroed long-video end cards: the QR code encodes ${SITE}/z/<series-slug>; each lands on ${dest} tagged per series.`];
  const pad = Math.max(...series.map((s) => s.slug.length)) + 5;
  const row = (from, campaign) => `${from.padEnd(pad + 4)} ${to(campaign)}   302`;
  lines.push(row('/z', 'yt-z'), row('/z/', 'yt-z'));
  for (const s of series) {
    lines.push(`# ${s.name}`);
    lines.push(row(`/z/${s.slug}`, `yt-z-${s.slug}`), row(`/z/${s.slug}/`, `yt-z-${s.slug}`));
  }
  lines.push(END);
  return lines.join('\n');
}

function splice(text, generated) {
  const a = text.indexOf(BEGIN);
  const b = text.indexOf(END);
  if (a === -1 && b === -1) return `${text.replace(/\s*$/, '')}\n\n${generated}\n`;
  if (a === -1 || b === -1 || b < a) throw new Error('zeroed-qr: public/_redirects has a broken BEGIN/END zeroed-qr block');
  return text.slice(0, a) + generated + text.slice(b + END.length);
}

const args = new Set(process.argv.slice(2));
const cfg = load();
if (args.has('--list')) {
  for (const s of cfg.series) console.log(`${s.slug.padEnd(24)} ${SITE}/z/${s.slug}`);
  process.exit(0);
}
const current = readFileSync(REDIRECTS, 'utf8');
const next = splice(current, block(cfg));
if (args.has('--check')) {
  if (next !== current) {
    console.error('zeroed-qr: public/_redirects is out of date with src/data/zeroed-qr.json. Run: node scripts/zeroed-qr-links.mjs');
    process.exit(1);
  }
  console.log(`zeroed-qr: ${cfg.series.length} series short links in step`);
} else {
  writeFileSync(REDIRECTS, next);
  console.log(`zeroed-qr: wrote ${cfg.series.length * 2 + 2} rules to public/_redirects`);
}
